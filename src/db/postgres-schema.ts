/**
 * Postgres schema bootstrap.
 *
 * The built-in tables are declared once in `system-schema.ts` with Drizzle's
 * SQLite builders. Re-declaring them for `pg-core` would drift, so this module
 * derives Postgres DDL from the same definitions. Columns keep SQLite's storage
 * contract (dates and JSON as `text`, booleans as `integer` 0/1) because both
 * the synchronous SQLite path and every service read those values as JS
 * strings/numbers. Only the identity column and the index/view syntax differ.
 *
 * Document tables (one per Appwrite collection) are created at runtime by
 * `push.ts`; the same generators below produce their Postgres DDL so the schema
 * push can eventually run on either backend.
 */
import { is, SQL, type Column } from 'drizzle-orm'
import { getTableConfig, type SQLiteTable } from 'drizzle-orm/sqlite-core'

import { collectionVersionKey } from '~/cluster/versions'
import type { PostgresDriver } from './postgres-driver'
import * as schema from './system-schema'
import { ftsTableName, permsTableName, type Attribute, type Index } from '~/schema/types'

const q = (name: string) => `"${name.replace(/"/g, '""')}"`
const literal = (value: string) => `'${value.replace(/'/g, "''")}'`

/** Storage-compatible Postgres type for a Drizzle SQLite column. */
function postgresType(column: Column): string {
  switch (column.getSQLType()) {
    case 'integer':
      return 'integer'
    case 'real':
    case 'double':
      return 'double precision'
    case 'blob':
      return 'bytea'
    case 'numeric':
      return 'numeric'
    case 'boolean':
      // The application reads and writes 0/1, not true/false.
      return 'integer'
    default:
      return 'text'
  }
}

/** Render a Drizzle `.default(...)` as a Postgres literal. */
function renderDefault(column: Column): string | null {
  if (!column.hasDefault) return null
  const value = column.default
  if (value === undefined || value === null) return null
  if (typeof value === 'boolean') return value ? '1' : '0'
  if (typeof value === 'number' || typeof value === 'bigint') return String(value)
  if (typeof value === 'string') return literal(value)
  if (value instanceof Date) return `${literal(value.toISOString())}::timestamptz`
  if (is(value, SQL)) {
    const chunks = (value as unknown as { queryChunks?: Array<{ value?: unknown }> }).queryChunks ?? []
    const text = chunks
      .map((chunk) => {
        const raw = (chunk as { value?: unknown }).value
        return Array.isArray(raw) ? raw.join('') : typeof raw === 'string' ? raw : ''
      })
      .join('')
    return text || null
  }
  return null
}

function columnDefinition(column: Column): string {
  const parts = [q(column.name), postgresType(column)]
  if ((column as { autoIncrement?: boolean }).autoIncrement) parts.push('GENERATED BY DEFAULT AS IDENTITY')
  if (column.notNull) parts.push('NOT NULL')
  const fallback = renderDefault(column)
  if (fallback !== null) parts.push(`DEFAULT ${fallback}`)
  if (column.primary) parts.push('PRIMARY KEY')
  if ((column as { isUnique?: boolean }).isUnique) parts.push('UNIQUE')
  return parts.join(' ')
}

/** The built-in tables, in declaration order. */
function drizzleTables(): SQLiteTable[] {
  const tables: SQLiteTable[] = []
  for (const value of Object.values(schema)) {
    try {
      getTableConfig(value as SQLiteTable)
      tables.push(value as SQLiteTable)
    } catch {
      // Not a table (a helper export, if one is added later).
    }
  }
  return tables
}

/** Postgres `CREATE TABLE IF NOT EXISTS` for every built-in table. */
export function postgresSystemStatements(): string[] {
  const statements: string[] = []
  for (const table of drizzleTables()) {
    const config = getTableConfig(table)
    const columns = config.columns.map(columnDefinition).join(',\n  ')
    statements.push(`CREATE TABLE IF NOT EXISTS ${q(config.name)} (\n  ${columns}\n)`)
  }
  return statements
}

/** Indexes declared next to the built-in tables. */
export function postgresSystemIndexStatements(): string[] {
  const statements: string[] = []
  for (const table of drizzleTables()) {
    const config = getTableConfig(table)
    for (const index of config.indexes) {
      const columns = index.config.columns.map((column) => q((column as Column).name)).join(', ')
      const unique = index.config.unique ? 'UNIQUE ' : ''
      statements.push(`CREATE ${unique}INDEX IF NOT EXISTS ${q(index.config.name)} ON ${q(config.name)} (${columns})`)
    }
  }
  return statements
}

/** The built-in tables with their columns, for the Postgres column migration. */
export function drizzleTableDefinitions(): Array<{ name: string; columns: Column[] }> {
  return drizzleTables().map((table) => {
    const config = getTableConfig(table)
    return { name: config.name, columns: config.columns }
  })
}

