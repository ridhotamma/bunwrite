/** `[version counter, table]` for the caches each table feeds. Mirrors `cluster-schema.ts`. */
const VERSIONED: [string, string][] = [
  ['schema', '_databases'],
  ['schema', '_collections'],
  ['settings', '_settings'],
  ['catalog', '_sites'],
  ['catalog', '_proxy_rules'],
  ['projects', '_projects'],
  ['auth', '_sessions'],
  ['auth', '_users'],
  ['auth', '_memberships'],
  ['auth', '_teams'],
  ['keys', '_api_keys'],
]

/** One function bumps any `_meta` counter; each trigger passes its key as an argument. */
export const POSTGRES_VERSION_FUNCTION = `CREATE OR REPLACE FUNCTION bunwrite_bump_version() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  INSERT INTO "_meta" ("key", "value") VALUES (TG_ARGV[0], 1)
  ON CONFLICT ("key") DO UPDATE SET "value" = "_meta"."value" + 1;
  RETURN NULL;
END;
$$`

/** Triggers that keep the cache counters current on Postgres. */
export function postgresVersionTriggerStatements(): string[] {
  const statements: string[] = []
  for (const [version, table] of VERSIONED) {
    for (const event of ['INSERT', 'UPDATE', 'DELETE']) {
      const name = `_meta_${table}_${event.toLowerCase()}`
      statements.push(`DROP TRIGGER IF EXISTS ${q(name)} ON ${q(table)}`)
      statements.push(`CREATE TRIGGER ${q(name)} AFTER ${event} ON ${q(table)} FOR EACH ROW EXECUTE FUNCTION bunwrite_bump_version(${literal(version)})`)
    }
  }
  return statements
}

/** The trigger that bumps one collection's list-cache version. */
export function postgresCollectionVersionStatements(databaseId: string, collectionId: string, table: string): string[] {
  const key = literal(collectionVersionKey(databaseId, collectionId))
  const statements: string[] = []
  for (const event of ['INSERT', 'UPDATE', 'DELETE'] as const) {
    const suffix = event === 'INSERT' ? 'ai' : event === 'UPDATE' ? 'au' : 'ad'
    const name = `${table}__version_${suffix}`
    statements.push(`DROP TRIGGER IF EXISTS ${q(name)} ON ${q(table)}`)
    statements.push(`CREATE TRIGGER ${q(name)} AFTER ${event} ON ${q(table)} FOR EACH ROW EXECUTE FUNCTION bunwrite_bump_version(${key})`)
  }
  return statements
}

/** Postgres type for an Appwrite attribute (see `schema/push.ts`). */
export function postgresAttributeType(attribute: Attribute): string {
  if (attribute.array) return 'text'
  switch (attribute.type) {
    case 'integer':
    case 'boolean':
      return 'integer'
    case 'double':
      return 'double precision'
    default:
      return 'text'
  }
}

const SYSTEM_COLUMNS = `"_seq" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "_id" text NOT NULL UNIQUE,
  "_createdAt" text NOT NULL,
  "_updatedAt" text NOT NULL,
  "_permissions" text NOT NULL DEFAULT '[]',
  "_rev" integer NOT NULL DEFAULT 1`

function attributeColumns(attributes: Attribute[]): string {
  return attributes.map((attribute) => `,\n  ${q(attribute.key)} ${postgresAttributeType(attribute)}`).join('')
}

/**
 * Create one collection's document table and its permission table, matching the
 * SQLite layout produced by `push.ts`.
 */
export function postgresDocumentTableStatements(table: string, attributes: Attribute[]): string[] {
  const perms = permsTableName(table)
  return [
    `CREATE TABLE IF NOT EXISTS ${q(table)} (\n  ${SYSTEM_COLUMNS}${attributeColumns(attributes)}\n)`,
    `CREATE TABLE IF NOT EXISTS ${q(perms)} (
      "doc" integer NOT NULL,
      "type" text NOT NULL,
      "role" text NOT NULL,
      PRIMARY KEY ("type", "role", "doc")
    )`,
    `CREATE INDEX IF NOT EXISTS ${q(perms + '_doc')} ON ${q(perms)} ("doc")`,
  ]
}

const SYSTEM_INDEX_COLUMNS: Record<string, string> = {
  $id: '_id',
  $createdAt: '_createdAt',
  $updatedAt: '_updatedAt',
  $sequence: '_seq',
}

/**
 * Indexes for a document table. `fulltext` becomes a GIN tsvector index; the
 * FTS5 maintenance triggers are SQLite-only.
 */
export function postgresDocumentIndexStatements(table: string, indexes: Index[], attributes: Attribute[]): string[] {
  const statements = [
    `CREATE INDEX IF NOT EXISTS ${q(`${table}__createdAt`)} ON ${q(table)} ("_createdAt")`,
    `CREATE INDEX IF NOT EXISTS ${q(`${table}__updatedAt`)} ON ${q(table)} ("_updatedAt")`,
  ]
  const attributeMap = new Map(attributes.map((attribute) => [attribute.key, attribute]))
  for (const index of indexes) {
    if (index.type === 'fulltext') {
      const expression = index.attributes
        .map((key) => `coalesce(${q(Object.hasOwn(SYSTEM_INDEX_COLUMNS, key) ? SYSTEM_INDEX_COLUMNS[key]! : key)}, '')`)
        .join(` || ' ' || `)
      statements.push(`CREATE INDEX IF NOT EXISTS ${q(ftsTableName(table, index.key))} ON ${q(table)} USING GIN (to_tsvector('english', ${expression}))`)
      continue
    }
    const columns = index.attributes.map((key, i) => {
      const system = Object.hasOwn(SYSTEM_INDEX_COLUMNS, key) ? SYSTEM_INDEX_COLUMNS[key] : undefined
      const column = system ?? key
      if (!system && !attributeMap.has(key)) {
        throw new Error(`Index ${index.key} on ${table} uses unknown attribute ${key}`)
      }
      const order = (index.orders[i] ?? 'ASC').toUpperCase() === 'DESC' ? ' DESC' : ''
      return q(column) + order
    })
    const unique = index.type === 'unique' ? 'UNIQUE ' : ''
    statements.push(`CREATE ${unique}INDEX IF NOT EXISTS ${q(`${table}__idx_${index.key}`)} ON ${q(table)} (${columns.join(', ')})`)
  }
  return statements
}

export interface PostgresSchemaOptions {
  log?: (line: string) => void
}

/**
 * Create or update the full Postgres schema.
 *
 * A transaction-level advisory lock serialises workers that boot together, the
 * same role the file lock plays for SQLite migrations.
 */
export async function ensurePostgresSchema(driver: PostgresDriver, options: PostgresSchemaOptions = {}): Promise<void> {
  const log = options.log ?? (() => {})
  await driver.ensureSchema()
  await driver.transaction(async (tx) => {
    await tx.exec(`SELECT pg_advisory_xact_lock(hashtext('bunwrite:postgres-schema'))`)
    for (const statement of postgresSystemStatements()) await tx.exec(statement)
    for (const statement of postgresSystemIndexStatements()) await tx.exec(statement)
    for (const statement of POSTGRES_CLUSTER_STATEMENTS) await tx.exec(statement)
    // Millisecond timestamps do not fit in int4. These ALTERs are idempotent
    // and also upgrade databases created before the columns became bigint.
    await tx.exec(`ALTER TABLE "_rate_limits" ALTER COLUMN "reset_at" TYPE bigint`)
    await tx.exec(`ALTER TABLE "_cluster_leases" ALTER COLUMN "expires_at" TYPE bigint`)
    for (const statement of POSTGRES_VIEW_STATEMENTS) await tx.exec(statement)
    await tx.exec(POSTGRES_VERSION_FUNCTION)
    for (const statement of postgresVersionTriggerStatements()) await tx.exec(statement)
    log('postgres schema is current')
  })
  await migratePostgresColumns(driver, options)
}

/** A column added to an existing table cannot carry identity/primary/unique. */
function columnAddDefinition(column: Column): string {
  const parts = [q(column.name), postgresType(column)]
  if (column.notNull) parts.push('NOT NULL')
  const fallback = renderDefault(column)
  if (fallback !== null) parts.push(`DEFAULT ${fallback}`)
  return parts.join(' ')
}

/**
 * Add columns that a newer version introduced, without touching existing data.
 *
 * Postgres needs a `NOT NULL` column to come with a default; the built-in
 * tables always have one, and a column without one is added as nullable and
 * reported so an operator can backfill it.
 */
export async function migratePostgresColumns(driver: PostgresDriver, options: PostgresSchemaOptions = {}): Promise<void> {
  const log = options.log ?? (() => {})
  const rows = await driver.all<{ table_name: string; column_name: string }>(
    `SELECT table_name, column_name FROM information_schema.columns WHERE table_schema = current_schema()`,
  )
  const existing = new Map<string, Set<string>>()
  for (const row of rows) {
    const set = existing.get(row.table_name) ?? new Set<string>()
    set.add(row.column_name)
    existing.set(row.table_name, set)
  }
  for (const table of drizzleTableDefinitions()) {
    const present = existing.get(table.name)
    if (!present) continue
    for (const column of table.columns) {
      if (present.has(column.name)) continue
      const definition = columnAddDefinition(column)
      try {
        await driver.exec(`ALTER TABLE ${q(table.name)} ADD COLUMN ${definition}`)
        log(`+ column ${table.name}.${column.name}`)
      } catch (error) {
        log(`! could not add ${table.name}.${column.name}: ${error instanceof Error ? error.message : String(error)}`)
      }
    }
  }
}
